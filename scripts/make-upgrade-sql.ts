/**
 * Writes database/upgrade-v3.12.sql from src/server/schema-upgrades.ts and
 * refreshes the same block at the end of database/database.sql.
 *   npx tsx scripts/make-upgrade-sql.ts
 * Each statement checks information_schema first, so the file can be run on
 * any older store (v3.1 … v3.11) — and run twice — without a single error.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url'; // v3.14 — works when the folder name has spaces
import { SCHEMA_COLUMNS, SCHEMA_INDEXES, SCHEMA_TABLES } from '../src/server/schema-upgrades.ts';

const q = (text: string) => text.replace(/\\/g, '\\\\').replace(/'/g, "''");
const guarded = (check: string, statement: string) =>
  `SET @s = (SELECT IF(COUNT(*) = 0, '${q(statement)}', 'DO 0') FROM ${check});\nPREPARE st FROM @s; EXECUTE st; DEALLOCATE PREPARE st;`;

const lines: string[] = [];
lines.push('-- Tables');
for (const table of SCHEMA_TABLES) lines.push(`${table.ddl.replace(/\n\s+/g, '\n  ').trim()};`, '');
lines.push('-- Columns (each one is added only when it is missing)');
for (const col of SCHEMA_COLUMNS) {
  lines.push(
    guarded(
      `information_schema.COLUMNS WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = '${col.table}' AND COLUMN_NAME = '${col.column}'`,
      `ALTER TABLE \`${col.table}\` ADD COLUMN \`${col.column}\` ${col.ddl}`
    )
  );
}
lines.push('', '-- Indexes');
for (const idx of SCHEMA_INDEXES) {
  lines.push(
    guarded(
      `information_schema.STATISTICS WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = '${idx.table}' AND INDEX_NAME = '${idx.name}'`,
      `ALTER TABLE \`${idx.table}\` ADD INDEX \`${idx.name}\` ${idx.ddl}`
    )
  );
}
const body = lines.join('\n');

const header = `-- ============================================================
-- Upgrade an EXISTING store (v3.1 … v3.13) to v3.14 — one file for every step
-- (the file keeps its v3.12 name so older guides still point to it; v3.14
-- adds the two live chat tables)
--
-- Not normally needed: the server adds these tables and columns by itself
-- when it starts (System Configuration -> Database & Cache -> Repair runs the
-- same upgrade). Use this file only if your database user is not allowed to
-- CREATE or ALTER tables: phpMyAdmin -> your database -> SQL -> paste -> Go.
--
-- Everything here is additive. No table is dropped or emptied and no
-- product, order, customer, stock or POS record is changed or deleted.
-- Every column and index is checked first, so the file runs without errors
-- on any older version and can safely be run more than once.
-- (Generated by scripts/make-upgrade-sql.ts.)
-- ============================================================

SET NAMES utf8mb4;

`;
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
fs.writeFileSync(path.join(root, 'database', 'upgrade-v3.12.sql'), header + body + '\n');
// The older single-file upgrades are replaced by this one
fs.rmSync(path.join(root, 'database', 'upgrade-v3.9.sql'), { force: true });
fs.rmSync(path.join(root, 'database', 'upgrade-v3.11.sql'), { force: true });

const START = '-- >>> v3.2 – v3.12 additions (generated) >>>';
const END = '-- <<< v3.2 – v3.12 additions <<<';
const dbFile = path.join(root, 'database', 'database.sql');
let full = fs.readFileSync(dbFile, 'utf8');
// Earlier releases wrote the same block under an older marker
const markers = [START, '-- >>> v3.2 – v3.11 additions (generated) >>>', '-- >>> v3.2 – v3.9 additions (generated) >>>'];
const at = markers.map((marker) => full.indexOf(marker)).filter((index) => index !== -1).sort((a, b) => a - b)[0] ?? -1;
if (at !== -1) full = full.slice(0, at).trimEnd() + '\n';
full += `\n${START}\n-- Everything later versions added, so a fresh import is complete even when\n-- the app is not allowed to ALTER tables. Safe to run on an existing database.\n${body}\n${END}\n`;
fs.writeFileSync(dbFile, full);
console.log(`upgrade-v3.12.sql: ${SCHEMA_TABLES.length} tables, ${SCHEMA_COLUMNS.length} columns, ${SCHEMA_INDEXES.length} indexes`);
